"""Math essays must stay in step with their sources, their numbers and the build.

content/musings/<slug>.md is generated by scripts/render_math.py from
content-src/musings/<slug>.md and static/musings/<slug>/numbers.py. These checks
need no pandoc: staleness is detected from the digest the generator records.
Run after `zola build`, like the other tests here.
"""
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))
import render_math  # noqa: E402  (the generator's own tokenizer counts the formulas)

VOID={'mspace','mprescripts','none'}
class Page(HTMLParser):
    """Counts the formulas of a built page and checks that every one is well nested."""
    def __init__(self,text):
        super().__init__(); self.stack=[]; self.formulas=0; self.broken=[]; self.stylesheets=[]; self.meta=[]; self.in_meta=False; self.feed(text)
    def handle_starttag(self,tag,attrs):
        attrs=dict(attrs)
        if tag=='link' and attrs.get('rel')=='stylesheet': self.stylesheets.append(attrs.get('href',''))
        if tag=='div' and attrs.get('class')=='article-head__meta': self.in_meta=True
        if tag=='math': self.formulas+=1
        if (tag=='math' or self.stack) and tag not in VOID: self.stack.append(tag)
    def handle_endtag(self,tag):
        if tag=='div': self.in_meta=False
        if not self.stack or tag in VOID: return
        if self.stack[-1]!=tag: self.broken.append((self.stack[-1],tag))
        self.stack.pop()
    def handle_data(self,text):
        if self.in_meta: self.meta.append(text)

def split(path):
    text=path.read_text(encoding='utf-8'); front,body=text[4:].split('\n+++\n',1)
    return front,body

class MathEssays(unittest.TestCase):
    def test_sources_numbers_and_build_agree(self):
        sources=sorted((ROOT/'content-src/musings').glob('*.md'))
        self.assertTrue(sources)
        for source in sources:
            slug=source.stem
            with self.subTest(essay=slug):
                script=ROOT/'static/musings'/slug/'numbers.py'
                result=json.loads(subprocess.run([sys.executable,str(script),'--json'],capture_output=True,text=True,check=True).stdout)
                self.assertTrue(result['all_passed'],[c['name'] for c in result['checks'] if not c['ok']])

                front,body=split(ROOT/'content/musings'/source.name)
                digest=hashlib.sha256(source.read_bytes()+script.read_bytes()).hexdigest()
                self.assertIn(f'# source-sha256: {digest}',front,'stale: re-run scripts/render_math.py')
                source_body=split(source)[1]
                formulas=sum(1 for m in render_math.TOKEN.finditer(source_body) if m.group('display') is not None or m.group('inline') is not None)
                self.assertEqual(body.count('<math'),formulas)
                self.assertNotRegex(body,r'\[\[n:|\$')
                self.assertNotIn('{{',body)  # would be read by Zola as a shortcode
                used=set(render_math.PLACEHOLDER.findall(source_body))
                self.assertEqual(used,set(result['numbers']),'every number is on the page and every placeholder is computed')

                page=Page((ROOT/'public/musings'/slug/'index.html').read_text(encoding='utf-8'))
                self.assertEqual(page.formulas,formulas)
                self.assertEqual(page.broken,[])
                self.assertEqual(page.stack,[])
                self.assertTrue(any('/assets/math.css' in href for href in page.stylesheets),page.stylesheets)
                minutes=tomllib.loads(front)['extra']['reading_time']
                self.assertIn(f'{minutes} min read',' '.join(''.join(page.meta).split()))
                self.assertEqual((ROOT/'public/musings'/slug/'numbers.py').read_bytes(),script.read_bytes())
    def test_other_musings_keep_zolas_reading_time(self):
        listing=(ROOT/'public/musings/index.html').read_text(encoding='utf-8')
        self.assertGreaterEqual(len(re.findall(r'\d+ min read',listing)),2)
if __name__=='__main__': unittest.main()
